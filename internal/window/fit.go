// Package window подбирает размер окна приложения под экран
package window

// defaultDPI - плотность, в которой Wails задаёт размеры окна (100% масштаба)
const defaultDPI = 96

// FitHeight возвращает высоту окна в логических пикселях (96 DPI).
// want - нужная высота, workPx - высота рабочей области монитора
// (без панели задач) в физических пикселях, dpi - плотность окна.
// Если окно помещается, высота остаётся прежней, иначе она уменьшается
// до рабочей области, а недостающее место страница добирает прокруткой.
// Деление с округлением вниз, как в Wails: окно не выйдет за край
// даже на пиксель
func FitHeight(want, workPx, dpi int) int {
	if workPx <= 0 || dpi <= 0 {
		return want
	}
	return min(want, workPx*defaultDPI/dpi)
}
