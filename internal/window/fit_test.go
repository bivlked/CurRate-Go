package window

import "testing"

func TestFitHeight(t *testing.T) {
	tests := []struct {
		name   string
		want   int
		workPx int
		dpi    int
		expect int
	}{
		// Рабочая область = высота экрана минус панель задач 48 логических px
		{"1080p 100%: 1080-48, помещается", 822, 1032, 96, 822},
		{"1440p 150%: 1440-72 = 1368, помещается", 822, 1368, 144, 822},
		{"ровно по рабочей области", 822, 822, 96, 822},
		{"720p 100%: панель задач 48 px", 822, 672, 96, 672},
		{"768p 100%", 822, 720, 96, 720},
		{"1080p 150%: (1080-72)/1.5 = 672", 822, 1008, 144, 672},
		{"1080p 125%: (1080-60)/1.25 = 816", 822, 1020, 120, 816},
		{"2160p 150%: 2160-72 = 2088, помещается", 822, 2088, 144, 822},
		{"дробное округляется вниз", 822, 1000, 120, 800},
		{"маленькая область: окно не выходит за край", 822, 300, 96, 300},
		{"маленькая область при 150%", 822, 672, 144, 448},
		{"нет данных о высоте", 822, 0, 96, 822},
		{"нет данных о DPI", 822, 672, 0, 822},
		{"отрицательные значения", 822, -5, -1, 822},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := FitHeight(tt.want, tt.workPx, tt.dpi); got != tt.expect {
				t.Errorf("FitHeight(%d, %d, %d) = %d, want %d", tt.want, tt.workPx, tt.dpi, got, tt.expect)
			}
		})
	}
}
